public class BooleanConditions {
    void checkIfEq(boolean condition) {
        if (condition) {
            System.out.println("ok");
        } else {
            System.out.println("not ok");
        }
    }

    void checkIfNe(boolean condition) {
        if (!condition) {
            System.out.println("not ok");
        } else {
            System.out.println("ok");
        }
    }
}
